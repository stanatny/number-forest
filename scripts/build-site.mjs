import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, '.local', 'site');
const runtime = ['index.html', 'src', 'styles', 'assets', 'sw.js', 'LICENSE'];
const releaseInputs = [...runtime, 'package.json', 'scripts/build-site.mjs'];
const { version } = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
if (typeof version !== 'string' || !/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(version)) throw new Error('package.json must contain a valid release version.');
const changes = execFileSync('git', ['status', '--porcelain', '--untracked-files=all', '--', ...releaseInputs], { cwd: root, encoding: 'utf8' });
if (changes.trim()) throw new Error('Commit the runtime files before preparing a release snapshot.');
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
for (const entry of runtime) await cp(path.join(root, entry), path.join(output, entry), { recursive: true });
await writeFile(path.join(output, '.nojekyll'), '');
await writeFile(path.join(output, 'version.json'), JSON.stringify({ version, sourceCommit: commit }, null, 2) + '\n');
console.log(`Static site prepared in ${output}\nSource commit: ${commit}`);
