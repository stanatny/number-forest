import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ids = ['bonds', 'arithmetic', 'groups', 'sharing', 'clock', 'reverse'];
const sources = {};
for (const id of ids) sources[id] = 'data:image/svg+xml;base64,' + (await readFile(path.join(root, 'assets/badges', id + '.svg'))).toString('base64');
const body = `/* Generated by node scripts/build-badge-art.mjs. Keep SVG originals editable. */
(function (root) {
  'use strict';
  var sources = ${JSON.stringify(sources, null, 2)};
  var images = [];
  // Hold decoded images for the entire visit. Awards never wait for a network request.
  var ready = Promise.all(Object.values(sources).map(function (source) {
    var image = new Image(); images.push(image); image.src = source;
    return image.decode ? image.decode().catch(function () {}) : Promise.resolve();
  }));
  root.NumberForestBadgeArt = Object.freeze({ sources: Object.freeze(sources), ready: ready });
})(globalThis);
`;
const target = path.join(root, 'src/badge-art.js');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== body) throw new Error('Regenerate badge art with node scripts/build-badge-art.mjs');
} else await writeFile(target, body);
